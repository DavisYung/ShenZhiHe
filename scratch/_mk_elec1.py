def scan(path):
    t = io.open(path, encoding="utf-8").read()
    bad = t.count("\ufffd")
    blank = len(__import__("re").findall(r"_{3,}", t))
    print("  %s：U+FFFD=%d  殘留填空=%d" % (os.path.basename(path), bad, blank))
    return bad == 0 and blank == 0


