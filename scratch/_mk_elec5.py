def dump(path, obj):
    with io.open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("寫出 %s" % path)


def scan(path):
    t = io.open(path, encoding="utf-8").read()
    bad = t.count("\ufffd")
    blank = len(re.findall(r"_{3,}", t))
    print("  %s：U+FFFD=%d  殘留填空=%d" % (os.path.basename(path), bad, blank))
    return bad == 0 and blank == 0


