# ---------- 驗證 ----------
errors = []
seen = set()
for e in links:
    key = (e["from"], e["to"])
    if key in seen:
        errors.append("重複邊: %s -> %s" % key)
    seen.add(key)
    if e["from"] not in point_of_tid[e["from"].split("-")[0]]:
        errors.append("不存在的 from: " + e["from"])
    if e["to"] not in point_of_tid[e["to"].split("-")[0]]:
        errors.append("不存在的 to: " + e["to"])
    n = len(e["label"])
    if n < 4 or n > 12:
        errors.append("label 長度 %d 超出 4-12: %s" % (n, e["label"]))

pairs = Counter()
for e in links:
    a, b = e["from"].split("-")[0], e["to"].split("-")[0]
    pairs[tuple(sorted((a, b)))] += 1
for p, c in pairs.items():
    if c < 3 or c > 8:
        errors.append("課題對 %s 連結數 %d 超出 3-8" % (p, c))

if not (60 <= len(links) <= 90):
    errors.append("總數 %d 超出 60-90" % len(links))

if errors:
    print("驗證失敗：")
    for x in errors:
        print("  - " + x)
    sys.exit(1)

