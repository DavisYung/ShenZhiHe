def main():
    data = json.load(io.open(PT, encoding="utf-8"))
    els = data["elements"]
    n_h = 0
    for e in els:
        z = e["z"]
        if z in HKEAA:
            e["mass"] = HKEAA[z]
            e["hkeaa"] = True
            n_h += 1
        else:
            e["mass"] = MODERN.get(z, e.get("mass", ""))
            e["hkeaa"] = False
    data["subtitle"] = "118 種元素 · 中英對照 · 相對原子質量依香港考評局 HKDSE 週期表"
    data["source"] = "數值：香港考評局 HKDSE 化學科元素週期表（HKDSE-CHEM 1A-12）；元素中英文名：Dave Lo《English-Chinese Periodic Table of Elements》(2006)"
    data["massNote"] = "相對原子質量採香港考評局週期表數值；括號內為最穩定同位素的質量數。"
    data["note"] = "106-118 號不在考評局週期表內，數值沿用現代公認值，僅供參考。"
    io.open(PT, "w", encoding="utf-8").write(json.dumps(data, ensure_ascii=False, indent=1))
    print("written", PT, os.path.getsize(PT), "bytes")
    print("考評局數值：", n_h, "/", len(els))
    for z in (1, 6, 8, 17, 26, 28, 47, 53, 79, 92, 104, 105, 106, 118):
        e = [x for x in els if x["z"] == z][0]
        print("  ", z, e["sym"], e["cn"], e["mass"], "HKEAA" if e["hkeaa"] else "modern")


if __name__ == "__main__":
    main()
